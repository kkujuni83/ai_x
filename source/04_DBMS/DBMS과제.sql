DROP TABLE MEMBER CASCADE CONSTRAINTS;
DROP TABLE MEMBER_LEVEL CASCADE CONSTRAINTS;
DROP SEQUENCE MEMBER_MNO_SQ;

CREATE TABLE MEMBER_LEVEL (
    LEVELNO NUMBER PRIMARY KEY,
    LEVELNAME VARCHAR2(50) NOT NULL
);

CREATE TABLE MEMBER (
    mNO NUMBER PRIMARY KEY,
    mNAME VARCHAR2(50) NOT NULL,
    mPW VARCHAR2(8) NOT NULL,
    mMAIL VARCHAR2(50) UNIQUE NOT NULL,
    mPOINT NUMBER DEFAULT 0 CHECK (mPOINT >= 0),
    mRDATE DATE DEFAULT SYSDATE,
    LEVELNO NUMBER,
    CONSTRAINT fk_level FOREIGN KEY (LEVELNO) REFERENCES MEMBER_LEVEL(LEVELNO)
);

CREATE SEQUENCE MEMBER_MNO_SQ
START WITH 1
INCREMENT BY 1
NOCACHE;

