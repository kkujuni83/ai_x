SELECT 
    mNO AS "mNO",
    mNAME AS "mNAME",
    TO_CHAR(mRDATE, 'YYYY-MM-DD') AS "mRDATE",
    mMAIL AS "mMAIL",
    mPOINT AS "point",
    LEVELNAME AS "levelname"
FROM 
    MEMBER
JOIN 
    MEMBER_LEVEL ON MEMBER.LEVELNO = MEMBER_LEVEL.LEVELNO;
